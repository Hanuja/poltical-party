export function regText(lang, key, vars) {
  const s = (TEXT[lang] && TEXT[lang][key]) || TEXT.en[key] || key
  return vars ? s.replace(/\{(\w+)\}/g, (_, k) => (vars[k] ?? '')) : s
}

export function useRegText() {
  const { language } = useLanguage()
  return (key, vars) => regText(language, key, vars)
}

export const localeFor = (lang) => (lang === 'ta' ? 'ta-LK' : lang === 'si' ? 'si-LK' : 'en-GB')

/** '2026-12-10' → '10 December 2026' (in the reader's language) */
export function fmtDate(iso, lang, opts = {}) {
  if (!iso) return ''
  const d = new Date(`${String(iso).slice(0, 10)}T00:00:00`)
  if (Number.isNaN(d.getTime())) return iso
  return d.toLocaleDateString(localeFor(lang), { day: 'numeric', month: 'long', year: 'numeric', ...opts })
}
/** '11:00' → '11:00 AM' */
export function fmtTime(hhmm, lang) {
  if (!hhmm) return ''
  const [h, m] = String(hhmm).split(':').map(Number)
  const d = new Date(2000, 0, 1, h || 0, m || 0)
  return d.toLocaleTimeString(localeFor(lang), { hour: 'numeric', minute: '2-digit', hour12: true })
}
export const fmtTimeRange = (a, b, lang) => [fmtTime(a, lang), fmtTime(b, lang)].filter(Boolean).join(' – ')
/** '2026-11-21 09:30:12' → '21 November 2026, 9:30 AM' */
export function fmtDateTime(sqlDateTime, lang) {
  if (!sqlDateTime) return ''
  const d = new Date(String(sqlDateTime).replace(' ', 'T'))
  if (Number.isNaN(d.getTime())) return sqlDateTime
  return d.toLocaleString(localeFor(lang), { day: 'numeric', month: 'long', year: 'numeric', hour: 'numeric', minute: '2-digit', hour12: true })
}
